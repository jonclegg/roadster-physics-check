"""Write site/roadster/tank-tables.js: real-gas nitrogen blowdown tables for the Roadster physics page.

For each fill pressure the tank gas follows an isentrope (no heat from the walls) as it empties;
the isothermal table covers the other bound (walls keep the gas at 20 C). The page interpolates
pressure and temperature from the gas density left in the 600 L tank.

Run with a Python that has CoolProp: python3 scripts/roadster_tank_tables.py
"""
import json
from pathlib import Path

from CoolProp.CoolProp import PropsSI

PSI = 6894.757
FILL_TEMPERATURE = 293.15
FLUID = "Nitrogen"
FILL_PRESSURES_PSI = list(range(4000, 10001, 500))
SAMPLES = 120
OUTPUT = Path(__file__).resolve().parent.parent / "site" / "roadster" / "tank-tables.js"


def isentrope(fill_psi):
    fill_density = PropsSI("D", "P", fill_psi * PSI, "T", FILL_TEMPERATURE, FLUID)
    entropy = PropsSI("S", "P", fill_psi * PSI, "T", FILL_TEMPERATURE, FLUID)
    critical_temperature = PropsSI("Tcrit", FLUID)
    rows = []
    for index in range(SAMPLES + 1):
        density = fill_density * (1 - index / SAMPLES) ** 1.6
        if density < 0.5:
            break
        try:
            temperature = PropsSI("T", "D", density, "S", entropy, FLUID)
            pressure = PropsSI("P", "D", density, "S", entropy, FLUID)
        except ValueError:
            break  # the isentrope left the gas phase: the rest of the gas is unusable
        if temperature < critical_temperature and pressure >= PropsSI("P", "T", temperature, "Q", 1, FLUID):
            break
        rows.append([round(density, 3), round(pressure / PSI, 1), round(temperature, 2)])
    return {"fillPsi": fill_psi, "fillDensity": round(fill_density, 3), "rows": rows}


def isotherm():
    top = PropsSI("D", "P", 10000 * PSI, "T", FILL_TEMPERATURE, FLUID)
    rows = []
    for index in range(SAMPLES + 1):
        density = top * index / SAMPLES
        pressure = PropsSI("P", "D", max(density, 1e-3), "T", FILL_TEMPERATURE, FLUID)
        rows.append([round(density, 3), round(pressure / PSI, 1)])
    return rows


tables = {
    "fluid": FLUID,
    "fillTemperature": FILL_TEMPERATURE,
    "isentropes": [isentrope(psi) for psi in FILL_PRESSURES_PSI],
    "isotherm": isotherm(),
}
OUTPUT.write_text("// Generated by scripts/roadster_tank_tables.py (CoolProp real-gas nitrogen). Do not edit.\n"
                  f"window.TANK_TABLES = {json.dumps(tables, separators=(',', ':'))};\n")
print(f"Wrote {OUTPUT} ({OUTPUT.stat().st_size:,} bytes)")
